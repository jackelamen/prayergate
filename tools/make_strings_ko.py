#!/usr/bin/env python3
"""
Builds app/src/main/res/values-ko/strings.xml from tools/strings_ko_source.xml.

Run from the project root:   python3 tools/make_strings_ko.py

Why a script: Android may wrap Korean text in the middle of a word. Korean
puts spaces between words, so this script glues the letters of each word
together with an invisible "word joiner" (U+2060). Lines can then only break
at the spaces. It also checks that every English string has a Korean version.
"""
import os
import re

ROOT = os.path.join(os.path.dirname(__file__), "..")
SOURCE = os.path.join(ROOT, "tools", "strings_ko_source.xml")
ENGLISH = os.path.join(ROOT, "app", "src", "main", "res", "values", "strings.xml")
TARGET = os.path.join(ROOT, "app", "src", "main", "res", "values-ko", "strings.xml")

WORD_JOINER = "⁠"
HANGUL = "가-힣"


def names(xml: str) -> set:
    """The names of all translatable strings, plurals and arrays in a strings file."""
    found = set()
    for tag, name, attrs in re.findall(r'<(string|plurals|string-array) name="([^"]+)"([^>]*)>', xml):
        if 'translatable="false"' not in attrs:
            found.add(name)
    return found


def glue_words(text: str) -> str:
    """Puts a word joiner wherever a line break would split a word."""
    # Inside a Korean word: between two Hangul syllables.
    text = re.sub(f"(?<=[{HANGUL}])(?=[{HANGUL}])", WORD_JOINER, text)
    # Where a Korean ending follows English letters, a number, a closing
    # quote or bracket, or a placeholder: "PrayerGate가", "%1$d분", "\"제한된 설정\"을".
    text = re.sub(f"(?<=[A-Za-z0-9)\"'])(?=[{HANGUL}])", WORD_JOINER, text)
    return text


def main():
    source = open(SOURCE, encoding="utf-8").read()
    english = open(ENGLISH, encoding="utf-8").read()

    missing = names(english) - names(source)
    extra = names(source) - names(english)
    assert not missing, f"Korean is missing: {sorted(missing)}"
    assert not extra, f"Korean has strings that English does not: {sorted(extra)}"

    # Glue only the text between tags, never tag names or attributes.
    out = re.sub(r">([^<]+)<", lambda m: ">" + glue_words(m.group(1)) + "<", source)
    header = "<!-- GENERATED by tools/make_strings_ko.py from tools/strings_ko_source.xml. Edit that file instead. -->\n"
    out = out.replace("<resources>", header + "<resources>", 1)

    os.makedirs(os.path.dirname(TARGET), exist_ok=True)
    with open(TARGET, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"Wrote {len(names(source))} Korean strings to {os.path.relpath(TARGET, ROOT)}")


if __name__ == "__main__":
    main()
